CREATE TABLE IF NOT EXISTS public.users (
  user_id text NOT NULL,
  username text NOT NULL,
  first_seen timestamp with time zone DEFAULT now(),
  last_seen timestamp with time zone DEFAULT now(),
  message_count integer DEFAULT 0,
  achievements text[] DEFAULT '{}'::text[],
  created_at timestamp with time zone DEFAULT now(),
  CONSTRAINT users_pkey PRIMARY KEY (user_id)
);

CREATE TABLE IF NOT EXISTS public.stream_sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  started_at timestamp with time zone NOT NULL,
  ended_at timestamp with time zone,
  duration_minutes integer,
  game text,
  peak_viewers integer DEFAULT 0,
  total_messages integer DEFAULT 0,
  death_count integer DEFAULT 0,
  top_commands jsonb DEFAULT '{}'::jsonb,
  created_at timestamp with time zone DEFAULT now(),
  narrative jsonb,
  CONSTRAINT stream_sessions_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.stream_memory (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  session_id integer,
  stream_date date NOT NULL,
  game text,
  summary text,
  highlights text[] DEFAULT '{}'::text[],
  recurring_phrases text[] DEFAULT '{}'::text[],
  active_users text[] DEFAULT '{}'::text[],
  created_at timestamp with time zone DEFAULT now(),
  CONSTRAINT stream_memory_pkey PRIMARY KEY (id),
  CONSTRAINT stream_memory_session_id_fkey FOREIGN KEY (session_id) REFERENCES public.stream_sessions(id)
);

CREATE TABLE IF NOT EXISTS public.stream_highlights (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  session_id integer,
  detected_at timestamp with time zone DEFAULT now(),
  trigger_messages text[] DEFAULT '{}'::text[],
  marker_id text,
  description text,
  CONSTRAINT stream_highlights_pkey PRIMARY KEY (id),
  CONSTRAINT stream_highlights_session_id_fkey FOREIGN KEY (session_id) REFERENCES public.stream_sessions(id)
);

CREATE TABLE IF NOT EXISTS public.channel_stats (
  id integer NOT NULL DEFAULT 1 CHECK (id = 1),
  total_wins integer NOT NULL DEFAULT 0,
  total_losses integer NOT NULL DEFAULT 0,
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT channel_stats_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.channel_config (
  id text NOT NULL,
  broadcaster_token text,
  broadcaster_refresh_token text,
  updated_at timestamp with time zone DEFAULT now(),
  bot_token text,
  bot_refresh_token text,
  CONSTRAINT channel_config_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS public.cooldowns (
  key text NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  CONSTRAINT cooldowns_pkey PRIMARY KEY (key)
);

CREATE TABLE IF NOT EXISTS public.user_facts (
  username text NOT NULL,
  channel text NOT NULL DEFAULT 'parlusorum'::text,
  fact_type text NOT NULL,
  value text NOT NULL,
  updated_at timestamp with time zone DEFAULT now(),
  CONSTRAINT user_facts_pkey PRIMARY KEY (username, channel, fact_type)
);

-- El upsert del bot usa onConflict 'channel,term_key': necesita la restricción UNIQUE.
CREATE TABLE IF NOT EXISTS public.channel_lore (
  id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
  channel text NOT NULL,
  term text NOT NULL,
  term_key text NOT NULL,
  kind text NOT NULL DEFAULT 'meme'::text,
  status text NOT NULL DEFAULT 'pending'::text,
  needs_approval boolean NOT NULL DEFAULT false,
  streams_count integer NOT NULL DEFAULT 1,
  total_count integer NOT NULL DEFAULT 1,
  users text[] NOT NULL DEFAULT '{}'::text[],
  users_count integer NOT NULL DEFAULT 0,
  missed_streams integer NOT NULL DEFAULT 0,
  last_seen timestamp with time zone NOT NULL DEFAULT now(),
  last_stream_id text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT channel_lore_pkey PRIMARY KEY (id),
  CONSTRAINT channel_lore_channel_term_key_key UNIQUE (channel, term_key)
);

